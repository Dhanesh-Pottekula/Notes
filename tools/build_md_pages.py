#!/usr/bin/env python3
"""Turn every Markdown note into a readable HTML page beside it, so the home page can link it.

    python3 Notes/tools/build_md_pages.py      # then: python3 Notes/tools/build_home.py

- Converts each git-tracked *.md note (trading, programming, product thinking, ...) to <same name>.html
  in the same folder, in the look of tools/md_page.css, with the light/dark switch and highlights.
- Skips working files: AGENTS.md, BRIEF.md, AGENT_RULES.md, README.md, and everything under career/,
  tools/, illus/ and sources/ (career profile and job-search notes are private working material).
- The .md stays the source of truth: edit the .md, rerun this. A generated page starts with a marker
  comment; the script never overwrites an .html that does not carry the marker.
- No dependencies: the small Markdown reader below handles what the notes use (headings, paragraphs,
  bold/italic/code, links, lists with nesting, tables, fenced code, quotes, horizontal rules).
"""
import html, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
NOTES = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from theme_toggle import add_theme            # noqa: E402
from annotate_inject import add_annotate      # noqa: E402

MARK = "<!-- generated by tools/build_md_pages.py from "
SKIP_NAMES = {"AGENTS.md", "BRIEF.md", "AGENT_RULES.md", "README.md"}
SKIP_PARTS = {"career", "tools", "illus", "sources", "src", "node_modules"}
FONTS = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="stylesheet" '
         'href="https://fonts.googleapis.com/css2?family=Familjen+Grotesk:wght@500;600;700&family=Source+Serif+4:'
         'ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400&family=JetBrains+Mono:wght@400;600&display=swap">')


def notes_to_build():
    out = subprocess.run(["git", "-C", NOTES, "ls-files", "*.md"], capture_output=True, text=True, check=True).stdout
    keep = []
    for rel in out.splitlines():
        parts = rel.split("/")
        if parts[-1] in SKIP_NAMES or SKIP_PARTS & set(parts[:-1]):
            continue
        keep.append(rel)
    return sorted(keep)


# ---------- inline text ----------
def inline(text):
    """Markdown inside one block -> HTML. Code spans and links are set aside first so nothing inside them changes."""
    held = []

    def hold(s):
        held.append(s)
        return f"\x00{len(held) - 1}\x00"

    text = re.sub(r"(`+)(.+?)\1", lambda m: hold("<code>" + html.escape(m.group(2).strip(), quote=False) + "</code>"), text)
    text = re.sub(r"<(https?://[^\s<>]+)>", lambda m: hold(f'<a href="{html.escape(m.group(1))}">{html.escape(m.group(1))}</a>'), text)
    text = html.escape(text, quote=False)

    def link(m):
        label, url = m.group(1), m.group(2)
        if not re.match(r"[a-z]+:|#", url):                       # a relative link to another note
            url = re.sub(r"\.md(#|$)", r".html\1", url)
        return hold(f'<a href="{html.escape(url)}">{label}</a>')

    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)(?:\s+&quot;[^)]*)?\)", link, text)
    text = re.sub(r"(?<![\"'=>])(https?://[^\s<)\]]+[^\s<)\].,;:!?])", lambda m: hold(f'<a href="{m.group(1)}">{m.group(1)}</a>'), text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\w)__(.+?)__(?!\w)", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    text = re.sub(r"(?<!\w)_(?!\s)(.+?)(?<!\s)_(?!\w)", r"<em>\1</em>", text)
    text = re.sub(r"~~(.+?)~~", r"<del>\1</del>", text)
    while "\x00" in text:                                         # put the held pieces back (they can nest)
        text = re.sub(r"\x00(\d+)\x00", lambda m: held[int(m.group(1))], text)
    return text


def slug(text, used):
    s = re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", text).lower()).strip("-") or "section"
    base, n = s, 2
    while s in used:
        s, n = f"{base}-{n}", n + 1
    used.add(s)
    return s


# ---------- blocks ----------
LIST = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")


def split_row(line):
    line = line.strip()
    line = line[1:] if line.startswith("|") else line
    line = line[:-1] if line.endswith("|") and not line.endswith("\\|") else line
    return [c.strip().replace("\\|", "|") for c in re.split(r"(?<!\\)\|", line)]


def render_list(items):
    """items: [(indent, ordered, text)] -> nested <ul>/<ol>."""
    out, stack = [], []                                           # stack of (indent, tag)
    for indent, ordered, text in items:
        tag = "ol" if ordered else "ul"
        while stack and indent < stack[-1][0]:
            out.append(f"</li></{stack.pop()[1]}>")
        if stack and indent == stack[-1][0]:
            if stack[-1][1] != tag:                               # bullet list turns into a numbered one
                out.append(f"</li></{stack.pop()[1]}>")
                out.append(f"<{tag}>")
                stack.append((indent, tag))
            else:
                out.append("</li>")
        else:
            out.append(f"<{tag}>")
            stack.append((indent, tag))
        text = re.sub(r"^\[( |x|X)\]\s+", lambda m: "☑ " if m.group(1).strip() else "☐ ", text)
        out.append("<li>" + inline(text))
    while stack:
        out.append(f"</li></{stack.pop()[1]}>")
    return "".join(out)


def convert(md):
    """Markdown text -> (title, body html, [(id, heading text)] for h2)."""
    lines = md.replace("\r\n", "\n").expandtabs(4).split("\n")
    out, toc, used, title, i = [], [], set(), None, 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        m = re.match(r"^(```+|~~~+)\s*([\w+-]*)", line)
        if m:                                                     # fenced code
            fence, lang, j = m.group(1), m.group(2), i + 1
            while j < len(lines) and not lines[j].startswith(fence):
                j += 1
            cap = f'<figcaption><span class="lang">{html.escape(lang)}</span></figcaption>' if lang else ""
            code = html.escape("\n".join(lines[i + 1:j]), quote=False)
            out.append(f'<figure class="code">{cap}<pre><code>{code}</code></pre></figure>')
            i = j + 1
            continue
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:                                                     # heading
            level, text = len(m.group(1)), inline(m.group(2))
            if title is None and (level == 1 or not out):          # the first heading names the page
                title = text
            else:
                level = max(level, 2)                             # only one <h1> per page
                hid = slug(text, used)
                if level == 2:
                    toc.append((hid, text))
                out.append(f'<h{level} id="{hid}">{text}</h{level}>')
            i += 1
            continue
        if re.match(r"^\s*([-*_])(\s*\1){2,}\s*$", line):         # horizontal rule
            out.append("<hr>")
            i += 1
            continue
        if "|" in line and i + 1 < len(lines) and re.match(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$", lines[i + 1]):
            head, aligns = split_row(line), []                    # table
            for c in split_row(lines[i + 1]):
                aligns.append("center" if c.startswith(":") and c.endswith(":") else "right" if c.endswith(":") else "")
            j, rows = i + 2, []
            while j < len(lines) and lines[j].strip() and "|" in lines[j]:
                rows.append(split_row(lines[j]))
                j += 1

            def cell(tag, cells):
                tds = []
                for k, c in enumerate(cells):
                    a = aligns[k] if k < len(aligns) else ""
                    attr = f' style="text-align:{a}"' if a else ""
                    tds.append(f"<{tag}{attr}>{inline(c)}</{tag}>")
                return "<tr>" + "".join(tds) + "</tr>"

            out.append('<div class="tablewrap"><table class="md">' + cell("th", head) + "".join(cell("td", r) for r in rows) + "</table></div>")
            i = j
            continue
        if line.lstrip().startswith(">"):                         # quote
            j, buf = i, []
            while j < len(lines) and lines[j].lstrip().startswith(">"):
                buf.append(re.sub(r"^\s*>\s?", "", lines[j]))
                j += 1
            out.append('<blockquote class="box">' + convert("\n".join(buf))[1] + "</blockquote>")
            i = j
            continue
        if LIST.match(line):                                      # list (may nest; an item may wrap)
            items, j = [], i
            while j < len(lines):
                m = LIST.match(lines[j])
                if m:
                    items.append([len(m.group(1)), m.group(2)[0].isdigit(), m.group(3)])
                elif lines[j].strip() and lines[j].startswith(" ") and items:
                    items[-1][2] += " " + lines[j].strip()        # continuation of the item above
                elif not lines[j].strip() and j + 1 < len(lines) and (LIST.match(lines[j + 1]) or lines[j + 1].startswith("  ")):
                    pass                                          # blank line inside a loose list
                else:
                    break
                j += 1
            out.append(render_list(items))
            i = j
            continue
        j, buf = i, []                                            # paragraph: until a blank line or another block
        while j < len(lines) and lines[j].strip() and not re.match(r"^(#{1,6}\s|```|~~~|\s*>)", lines[j]) \
                and not (LIST.match(lines[j]) and j > i) and not (j > i and re.match(r"^\s*([-*_])(\s*\1){2,}\s*$", lines[j])):
            if j > i and "|" in lines[j] and j + 1 < len(lines) and re.match(r"^\s*\|?\s*:?-{2,}", lines[j + 1]):
                break
            buf.append(lines[j].strip())
            j += 1
        # Notes written one fact per line ("cmd -> what it does") keep their line breaks; wrapped prose is joined.
        wrapped = all(len(x) >= 55 for x in buf[:-1])               # prose hard-wrapped at a fixed width
        listy = len(buf) > 1 and not wrapped and (
            all(len(x) < 60 for x in buf) or sum("->" in x or "→" in x for x in buf) * 2 >= len(buf))
        out.append("<p>" + (inline("\n".join(buf)).replace("\n", "<br>\n") if listy else inline(" ".join(buf))) + "</p>")
        i = j
    return title, "\n".join(out), toc


def page(rel, md):
    title, body, toc = convert(md)
    name = os.path.basename(rel)
    title = title or name[:-3].replace("_", " ").replace("-", " ").capitalize()
    depth = rel.count("/")
    home = "../" * depth + "index.html"
    folder = os.path.dirname(rel).replace("/", " · ")
    toc_html = ""
    if len(toc) >= 3:
        toc_html = ('<section class="toc"><h2 class="toc-h">On this page</h2><ol>' +
                    "".join(f'<li><a href="#{i}">{re.sub("<[^>]+>", "", t)}</a></li>' for i, t in toc) + "</ol></section>")
    style = open(os.path.join(HERE, "md_page.css"), encoding="utf-8").read()
    plain_title = html.escape(html.unescape(re.sub("<[^>]+>", "", title)))
    return f"""<!DOCTYPE html>
{MARK}{name} : edit the .md and rerun, do not edit this file -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{plain_title}</title>
{FONTS}
<style>
{style}
</style>
</head>
<body>
<main>
<nav class="crumbs"><a href="{home}">← Notes home</a></nav>
<header class="hero">
<p class="kicker">{html.escape(folder)} · note</p>
<h1>{title}</h1>
</header>
{toc_html}
{body}
<nav class="crumbs"><a href="{home}">← Notes home</a></nav>
</main>
</body>
</html>
"""


def main():
    built, skipped = 0, []
    for rel in notes_to_build():
        src = os.path.join(NOTES, rel)
        dst = src[:-3] + ".html"
        if os.path.exists(dst) and MARK not in open(dst, encoding="utf-8", errors="replace").read(400):
            skipped.append(rel)                                   # a hand-made page owns that name
            continue
        doc = page(rel, open(src, encoding="utf-8").read())
        doc = add_annotate(add_theme(doc), dst)
        if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != doc:
            with open(dst, "w", encoding="utf-8") as f:
                f.write(doc)
        built += 1
    print(f"built {built} note pages")
    for rel in skipped:
        print(f"  skipped (a hand-made .html has the same name): {rel}")


if __name__ == "__main__":
    main()
